import html

import streamlit as st

from utils import AUTHOR_NAME, AUTHOR_ROLE, EMAIL, GITHUB_URL, LINKEDIN_URL, api_online, api_url

st.markdown(
    '<div class="page-title">About</div>'
    '<div class="page-sub">LeafDoctor AI is a computer-vision project that helps identify crop leaf '
    "diseases from a single photo.</div>",
    unsafe_allow_html=True,
)

links = []
if GITHUB_URL:
    links.append(f'<a class="chip link" href="{html.escape(GITHUB_URL)}" target="_blank">GitHub</a>')
if LINKEDIN_URL:
    links.append(f'<a class="chip link" href="{html.escape(LINKEDIN_URL)}" target="_blank">LinkedIn</a>')
if EMAIL:
    links.append(f'<a class="chip link" href="mailto:{html.escape(EMAIL)}">Email</a>')

st.markdown(
    '<div class="grid-2">'
    '<div class="card"><div class="card-title">Project</div>'
    '<p class="para">Upload a leaf photo and a PyTorch model fine-tuned on the PlantVillage dataset returns the '
    "crop, disease, confidence and general guidance. The model is trained on a Google Colab GPU and served "
    "through a FastAPI backend.</p>"
    '<span class="chip">PyTorch</span><span class="chip">EfficientNetV2</span>'
    '<span class="chip">FastAPI</span><span class="chip">Streamlit</span></div>'
    '<div class="card"><div class="card-title">Built by</div>'
    f'<div class="dname">{html.escape(AUTHOR_NAME)}</div>'
    f'<p class="para" style="margin-top:.3rem">{html.escape(AUTHOR_ROLE)}</p>'
    f'{"".join(links)}</div>'
    "</div>",
    unsafe_allow_html=True,
)

st.markdown(
    '<div class="section-head">Roadmap</div>'
    '<div class="card"><ul class="tip-list">'
    "<li>Add rice and other Bangladesh-relevant crops</li>"
    "<li>Fine-tune on real field photos for better robustness</li>"
    "<li>Grad-CAM heatmaps to show where the model looked</li>"
    "<li>Bangla language interface</li></ul></div>",
    unsafe_allow_html=True,
)

st.markdown('<div class="section-head">Connection</div>', unsafe_allow_html=True)
with st.expander("Backend settings"):
    new_url = st.text_input("Backend URL", value=api_url(), key="api_url_input")
    st.session_state["api_url"] = new_url.rstrip("/")
    st.caption("Connected." if api_online() else "Backend not reachable at this URL.")

st.markdown(
    '<div class="section-head">Disclaimer</div>'
    '<div class="card"><p class="para">Results are generated by a machine-learning model and may be wrong. '
    "Use them as a first screening and confirm with a local agriculture officer before applying any treatment.</p></div>",
    unsafe_allow_html=True,
)
